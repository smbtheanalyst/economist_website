'use client';

import React, { useState, useEffect } from 'react';
import { Mail, Eye, CheckCircle2, AlertTriangle, Loader2, X, RefreshCw } from 'lucide-react';

interface EmailLog {
  id: number;
  recipient_email: string;
  subject: string;
  html_body: string;
  text_body: string;
  email_type: string;
  delivery_status: 'captured_local' | 'sent_smtp' | 'failed';
  error_message: string;
  created_at: string;
}

export default function AdminEmailsPage() {
  const [logs, setLogs] = useState<EmailLog[]>([]);
  const [smtpConfigured, setSmtpConfigured] = useState(false);
  const [loading, setLoading] = useState(true);
  const [previewItem, setPreviewItem] = useState<EmailLog | null>(null);

  const fetchLogs = () => {
    setLoading(true);
    fetch('/api/admin/emails')
      .then((res) => res.json())
      .then((data) => {
        setLogs(data.logs || []);
        setSmtpConfigured(Boolean(data.smtpConfigured));
        setLoading(false);
      })
      .catch((err) => {
        console.error('Failed to load email logs:', err);
        setLoading(false);
      });
  };

  useEffect(() => {
    fetchLogs();
  }, []);

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row justify-between sm:items-center border-b border-[#D9DCD2] pb-4 gap-3">
        <div>
          <h2 className="font-serif text-2xl font-medium text-[#192B2A]">
            Outgoing Email Outbox Inspector
          </h2>
          <p className="text-xs text-[#52605A]">
            Audit and preview all transactional and notification emails generated by the platform.
          </p>
        </div>

        <div className="flex items-center gap-3">
          <div
            className={`px-3 py-1.5 rounded text-xs font-semibold border flex items-center gap-1.5 ${
              smtpConfigured
                ? 'bg-green-50 text-green-800 border-green-300'
                : 'bg-amber-50 text-amber-900 border-amber-300'
            }`}
          >
            {smtpConfigured ? (
              <>
                <CheckCircle2 className="w-3.5 h-3.5 text-green-700" />
                <span>Live SMTP Relay Active</span>
              </>
            ) : (
              <>
                <AlertTriangle className="w-3.5 h-3.5 text-amber-700" />
                <span>Local Capture Mode (Safe Dev Sandbox)</span>
              </>
            )}
          </div>

          <button
            onClick={fetchLogs}
            className="p-1.5 text-[#52605A] hover:text-[#285748] rounded border border-[#D9DCD2] bg-[#E9EDE4]"
            title="Refresh Outbox"
          >
            <RefreshCw className="w-4 h-4" />
          </button>
        </div>
      </div>

      {!smtpConfigured && (
        <div className="p-4 bg-amber-50 border border-amber-300 rounded text-xs text-amber-950 space-y-1">
          <p className="font-bold">Safe Local Email Capture Active:</p>
          <p className="text-[#52605A]">
            Live SMTP credentials are not configured in environment variables. All verification links, inquiry receipts, and booking notifications are safely captured here so you can test complete end-to-end user journeys locally without sending real emails.
          </p>
        </div>
      )}

      {loading ? (
        <div className="p-12 text-center text-sm text-[#52605A] flex items-center justify-center gap-2">
          <Loader2 className="w-5 h-5 animate-spin text-[#285748]" />
          <span>Loading outbox logs...</span>
        </div>
      ) : (
        <div className="bg-[#E9EDE4] border border-[#D9DCD2] rounded-sm overflow-x-auto">
          <table className="w-full text-left text-xs text-[#192B2A]">
            <thead className="bg-[#DCE3D7] border-b border-[#D9DCD2] text-[#52605A] font-semibold uppercase tracking-wider">
              <tr>
                <th className="p-3">Recipient</th>
                <th className="p-3">Subject</th>
                <th className="p-3">Type</th>
                <th className="p-3">Delivery Status</th>
                <th className="p-3">Timestamp (EAT)</th>
                <th className="p-3 text-right">Preview</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-[#D9DCD2]">
              {logs.map((log) => (
                <tr
                  key={log.id}
                  onClick={() => setPreviewItem(log)}
                  className="hover:bg-[#F7F5EF] transition-colors cursor-pointer"
                >
                  <td className="p-3 font-mono font-medium text-[#192B2A]">
                    {log.recipient_email}
                  </td>
                  <td className="p-3 font-medium max-w-xs truncate">{log.subject}</td>
                  <td className="p-3 font-mono text-[11px] text-[#52605A]">{log.email_type}</td>
                  <td className="p-3">
                    <span
                      className={`px-2 py-0.5 rounded text-[10px] font-bold uppercase tracking-wider ${
                        log.delivery_status === 'sent_smtp'
                          ? 'bg-green-100 text-green-900 border border-green-300'
                          : log.delivery_status === 'captured_local'
                          ? 'bg-blue-100 text-blue-900 border border-blue-300'
                          : 'bg-red-100 text-red-900 border border-red-300'
                      }`}
                    >
                      {log.delivery_status.replace('_', ' ')}
                    </span>
                  </td>
                  <td className="p-3 text-[#52605A] whitespace-nowrap">
                    {new Date(log.created_at).toLocaleString('en-GB')}
                  </td>
                  <td className="p-3 text-right">
                    <button
                      type="button"
                      className="px-2.5 py-1 text-xs font-semibold bg-[#285748] text-[#F7F5EF] rounded hover:bg-[#1e4337] inline-flex items-center gap-1"
                    >
                      <Eye className="w-3.5 h-3.5" />
                      <span>Inspect</span>
                    </button>
                  </td>
                </tr>
              ))}
              {logs.length === 0 && (
                <tr>
                  <td colSpan={6} className="p-8 text-center text-[#52605A]">
                    No outgoing emails recorded yet. Submit a question, book a slot, or subscribe to populate outbox.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      )}

      {/* Email Preview Modal */}
      {previewItem && (
        <div className="fixed inset-0 bg-black/50 z-50 flex items-center justify-center p-4 overflow-y-auto">
          <div className="bg-[#E9EDE4] border border-[#D9DCD2] w-full max-w-3xl rounded-sm p-6 space-y-4 max-h-[90vh] overflow-y-auto shadow-xl">
            <div className="flex justify-between items-center border-b border-[#D9DCD2] pb-3">
              <div>
                <span className="text-[10px] uppercase tracking-wider font-semibold text-[#285748]">
                  Email Outbox Record #{previewItem.id}
                </span>
                <h3 className="font-serif text-xl font-medium text-[#192B2A]">
                  {previewItem.subject}
                </h3>
              </div>
              <button onClick={() => setPreviewItem(null)} className="text-[#52605A]">
                <X className="w-5 h-5" />
              </button>
            </div>

            <div className="grid grid-cols-2 gap-2 text-xs bg-[#F7F5EF] p-3 rounded border border-[#D9DCD2]">
              <div>
                <span className="font-semibold text-[#192B2A]">To:</span>{' '}
                <span className="font-mono">{previewItem.recipient_email}</span>
              </div>
              <div>
                <span className="font-semibold text-[#192B2A]">Type:</span>{' '}
                <span className="font-mono">{previewItem.email_type}</span>
              </div>
              <div>
                <span className="font-semibold text-[#192B2A]">Status:</span>{' '}
                <span className="font-bold">{previewItem.delivery_status}</span>
              </div>
              <div>
                <span className="font-semibold text-[#192B2A]">Dispatched:</span>{' '}
                {new Date(previewItem.created_at).toLocaleString('en-GB')}
              </div>
            </div>

            {/* Rendered HTML Preview */}
            <div className="space-y-1">
              <span className="text-xs font-semibold text-[#192B2A]">Rendered HTML Body:</span>
              <div
                className="p-6 bg-white border border-[#D9DCD2] rounded shadow-inner max-h-80 overflow-y-auto"
                dangerouslySetInnerHTML={{ __html: previewItem.html_body }}
              />
            </div>

            {/* Plain text version */}
            <div className="space-y-1">
              <span className="text-xs font-semibold text-[#192B2A]">Plain Text Version:</span>
              <pre className="p-3 bg-[#F7F5EF] border border-[#D9DCD2] rounded text-xs text-[#192B2A] whitespace-pre-wrap font-mono max-h-36 overflow-y-auto">
                {previewItem.text_body}
              </pre>
            </div>

            <div className="flex justify-end pt-2 border-t border-[#D9DCD2]">
              <button
                onClick={() => setPreviewItem(null)}
                className="px-4 py-1.5 text-xs font-semibold bg-[#285748] text-white rounded"
              >
                Close Preview
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
